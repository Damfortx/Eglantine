/// "field+0xN" for a register index.
[[nodiscard]] inline std::string Maxwell3DRegName(u32 method) {
    const u32 byte_offset = method * 4;
    const auto it = std::upper_bound(kMaxwell3DRegNames.begin(), kMaxwell3DRegNames.end(),
                                     byte_offset,
                                     [](u32 value, const auto& entry) { return value < entry.first; });
    if (it == kMaxwell3DRegNames.begin()) {
        return fmt::format("{:#x}", method);
    }
    const auto& entry = *(it - 1);
    return byte_offset == entry.first ? std::string{entry.second}
                                      : fmt::format("{}+{:#x}", entry.second, byte_offset - entry.first);
}

